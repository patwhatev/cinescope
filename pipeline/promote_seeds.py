"""Fold starred keepers from out/grades.csv into seeds.txt as new seeds.

5 stars -> weight 1.0 (heavy: as diagnostic as your originally-stated seeds).
4 stars -> weight 0.5 (light: moves the model, but half as hard).
<=3     -> not promoted.

Everything above the "# --- promoted from grading ---" marker in seeds.txt is
yours — hand-authored seeds are never touched. Everything below it is fully
regenerated from grades.csv on every run, so lowering a star later removes
that seed next time this runs, and raising one updates its weight.
"""
import csv
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common

MARKER = "# --- promoted from grading (regenerated by pipeline/promote_seeds.py) ---"
PATH = os.path.join(common.ROOT, "seeds.txt")


def main():
    gpath = os.path.join(common.OUT, "grades.csv")
    if not os.path.exists(gpath):
        sys.exit("no grades.csv yet")
    with open(gpath, encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))

    promoted = []
    for r in rows:
        g = (r.get("grade") or "").strip()
        if not g:
            continue
        g = float(g)
        if g == 5:
            promoted.append((r["slug"], 1.0, r["title"], "heavy"))
        elif g == 4:
            promoted.append((r["slug"], 0.5, r["title"], "light"))

    text = open(PATH, encoding="utf-8").read() if os.path.exists(PATH) else ""
    head = text.split(MARKER)[0].rstrip("\n")
    hand_slugs = {ln.split("|")[0].strip() for ln in head.splitlines()
                  if ln.strip() and not ln.strip().startswith("#")}

    lines = [head, "", MARKER]
    skipped = 0
    for slug, weight, title, tier in sorted(promoted, key=lambda x: -x[1]):
        if slug in hand_slugs:
            skipped += 1   # a hand-authored seed also got graded highly — leave it alone
            continue
        lines.append("%-34s | %.1f | %s grading: %s (%s)" % (slug, weight, tier, title, slug))

    with open(PATH, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")

    heavy = sum(1 for _, w, _, _ in promoted if w == 1.0)
    light = sum(1 for _, w, _, _ in promoted if w == 0.5)
    print("seeds.txt: %d hand-authored seeds kept untouched" % len(hand_slugs))
    print("promoted %d heavy (1.0) + %d light (0.5) from grading%s"
          % (heavy, light, " (%d already hand-seeded, skipped)" % skipped if skipped else ""))


if __name__ == "__main__":
    main()
